describe('ciede2000', () => {
  it.each(SHARMA.map(([a, b, expected], i) => [i + 1, a, b, expected] as const))(
    'matches Sharma et al. pair %i',
    (_pair, a, b, expected) => {
      expect(ciede2000(a, b)).toBeCloseTo(expected, 4);
    },
  );

  it('is symmetric and zero for identical colors', () => {
    const a: Lab = [40, 30, -20];
    const b: Lab = [55, -10, 25];
    expect(ciede2000(a, b)).toBeCloseTo(ciede2000(b, a), 10);
    expect(ciede2000(a, a)).toBe(0);
  });
});

describe('sRGB and CIELAB', () => {
  it('converts reference colors', () => {
    const white = hexToLab('#FFFFFF');
    expect(white[0]).toBeCloseTo(100, 2);
    expect(Math.abs(white[1])).toBeLessThan(0.01);
    expect(Math.abs(white[2])).toBeLessThan(0.01);

    const red = rgbToLab([255, 0, 0]);
    expect(red[0]).toBeCloseTo(53.24, 1);
    expect(red[1]).toBeCloseTo(80.09, 1);
    expect(red[2]).toBeCloseTo(67.2, 1);
  });

  it('round-trips through hex', () => {
    for (const hex of ['#000000', '#FFFFFF', '#A8324A', '#1E3A8A', '#F5E6C8', '#6B2A3A']) {
      expect(labToHex(hexToLab(hex))).toBe(hex);
    }
  });

  it('measures hue distance on the circle', () => {
    expect(hueDistance(350, 10)).toBe(20);
    expect(hueDistance(0, 180)).toBe(180);
    expect(hueDistance(90, 300)).toBe(150);
  });
});
